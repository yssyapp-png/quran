class SurahIndexEntry {
  const SurahIndexEntry(
    this.number,
    this.name,
    this.verses,
    this.page,
    this.isMakki,
  );
  final int number;
  final String name;
  final int verses;
  final int page;
  final bool isMakki;

  String get revelationLabel => isMakki ? 'مكية' : 'مدنية';
  String get revelationSymbol => isMakki ? '🕋' : '🕌';
}

